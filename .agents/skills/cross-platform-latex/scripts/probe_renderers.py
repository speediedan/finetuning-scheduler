def _norm(s: str) -> str:
    """Collapse whitespace so multi-line and one-line forms of the same body compare equal."""
    return " ".join(s.split())


def classify(name: str, body: str | None) -> str:
    """Compare what reached the math engine against what the author wrote.

    The body is unescaped exactly once. A renderer writing '&' as '&amp;' in its HTML is correct
    encoding, and the math engine reading textContent sees '&'. A renderer that emits '&amp;lt;' is
    encoding twice, so the engine really does receive the string '&lt;' instead of '<' - that one is
    corruption, and the single unescape is what tells the two cases apart.
    """
    expected = CORPUS[name][1]
    if body is not None:
        body = html_mod.unescape(body)
    if body is None:
        return "no-math" if expected is not None else "no-math"
    if expected is None:
        return "altered"  # produced math where the author wrote prose
    return "verbatim" if _norm(body) == _norm(expected) else "altered"


def probe_myst():
    try:
        import myst_parser
        from markdown_it.renderer import RendererHTML
        from myst_parser.config.main import MdParserConfig
        from myst_parser.parsers.mdit import create_md_parser
    except ImportError:
        return None, None
    import re
    md = create_md_parser(
        MdParserConfig(enable_extensions={"dollarmath", "amsmath"}), RendererHTML
    )
    out = {}
    for name, (src, _exp) in CORPUS.items():
        html = md.render(src)
        m = re.search(r'class="math[^"]*"[^>]*>(.*?)</(?:span|div)>', html, re.S)
        out[name] = classify(name, m.group(1) if m else None)
    return out, f"myst-parser {myst_parser.__version__}"


def probe_mkdocs():
    try:
        import markdown
        import pymdownx
    except ImportError:
        return None, None
    import re
    md = markdown.Markdown(extensions=["pymdownx.arithmatex"])
    out = {}
    for name, (src, _exp) in CORPUS.items():
        md.reset()
        html = md.convert(src)
        m = re.search(r'type="math/tex[^"]*">(.*?)</script>', html, re.S)
        out[name] = classify(name, m.group(1) if m else None)
    return out, f"python-markdown {markdown.__version__} / pymdown-extensions {pymdownx.__version__}"


def probe_github():
    import re
    try:
        subprocess.run(["gh", "auth", "status"], capture_output=True, check=True)
    except (OSError, subprocess.CalledProcessError):
        return None, None
    out = {}
    for name, (src, _exp) in CORPUS.items():
        try:
            r = subprocess.run(
                ["gh", "api", "-X", "POST", "/markdown", "-f", "mode=gfm", "-f", f"text={src}"],
                capture_output=True, text=True, check=True,
            )
        except subprocess.CalledProcessError:
            return None, None
        m = re.search(r"<math-renderer[^>]*>(.*?)</math-renderer>", r.stdout, re.S)
        body = m.group(1) if m else None
        if body is not None:
            body = body.strip("$").strip()
        out[name] = classify(name, body)
    return out, "github.com markdown API (live)"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--report", action="store_true", help="flag disagreements with the recorded table")
    ap.add_argument("--json", action="store_true", help="emit machine-readable results")
    args = ap.parse_args()

    results, versions = {}, {}
    for key, fn in (("myst", probe_myst), ("mkdocs", probe_mkdocs), ("github", probe_github)):
        res, ver = fn()
        if res is None:
            print(f"# {key}: not available in this environment, skipped", file=sys.stderr)
            continue
        results[key], versions[key] = res, ver

    if not results:
        print("no renderers available; install myst-parser or pymdown-extensions, or authenticate gh")
        return 1

    if args.json:
        print(json.dumps({"versions": versions, "results": results}, indent=2))
        return 0

    engines = list(results)
    width = max(len(c) for c in CORPUS) + 2
    print("construct".ljust(width) + "".join(e.ljust(12) for e in engines))
    print("-" * (width + 12 * len(engines)))
    for name in CORPUS:
        print(name.ljust(width) + "".join(results[e][name].ljust(12) for e in engines))
    print()
    for e in engines:
        print(f"  {e}: {versions[e]}")

    rc = 0
    if args.report:
        drift = [
            (e, n, RECORDED[e][n], results[e][n])
            for e in engines for n in CORPUS
            if n in RECORDED.get(e, {}) and RECORDED[e][n] != results[e][n]
        ]
        print()
        if not any(RECORDED.values()):
            print("no baseline recorded yet; paste --json output into RECORDED to arm drift detection")
        elif not drift:
            print("matrix agrees with what the skill records")
        else:
            for e, n, was, now in drift:
                print(f"DRIFT {e}/{n}: skill records '{was}', measured '{now}'")
            print("\nUpdate references/platform-matrix.md and the affected guidance in SKILL.md.")
            rc = 1
    return rc


if __name__ == "__main__":
    sys.exit(main())
