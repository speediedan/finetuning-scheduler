#!/usr/bin/env python3
"""Re-measure how each renderer treats the constructs this skill has an opinion about.

The compatibility table in references/platform-matrix.md is a measurement with an expiry date: it
describes the renderer versions installed when it was taken, and a parser release can invalidate any
row. Rather than ask a reader to trust it, this regenerates it.

Engines are probed only if importable, so this degrades to whatever is present:
  Sphinx/MyST   needs myst-parser        (pip install myst-parser)
  MkDocs        needs pymdown-extensions (pip install markdown pymdown-extensions)
  GitHub        needs an authenticated `gh` CLI (renders through GitHub's real markdown API)

  probe_renderers.py            print the measured matrix
  probe_renderers.py --report   also flag cells that disagree with what the skill records

Run each engine from an interpreter that has it. When engines live in different environments, run
this once per environment; the matrix prints only the engines it could reach.
"""

