"""Keep the notebook tooling vendored from interpretune unmodified, and sync it from a chosen upstream commit.

``scripts/vendored/notebook_tooling/`` holds interpretune's repository-neutral notebook publisher, docs-artifact
renderer and nbstripout hook. They are configured from this repository's ``[tool.notebook-publishing]`` table and
must not be edited here: a local change is lost at the next sync, and the point of vendoring them is one source of
truth. Corrections go to interpretune; this repository then syncs.

Usage::

    python scripts/check_vendored_notebook_tooling.py              # offline: every file matches the manifest
    python scripts/check_vendored_notebook_tooling.py --sync <ref> # fetch the files at an interpretune commit
    python scripts/check_vendored_notebook_tooling.py --upstream [<ref>]   # compare with upstream (default: main)

The default check is offline and dependency-free so it can run as a pre-commit hook on a clean clone. Whether
upstream has moved on is a separate, networked question (``--upstream``), because a hook that needs the network
fails for reasons no contributor can act on.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
VENDOR_DIR = REPO / "scripts" / "vendored" / "notebook_tooling"
MANIFEST = VENDOR_DIR / "MANIFEST.sha256"
UPSTREAM_REPO = "speediedan/interpretune"
# vendored file name -> its path in the upstream repository
UPSTREAM_PATHS = {
    "notebook_publishing.py": "src/interpretune/utils/notebook_publishing.py",
    "notebook_docs.py": "src/interpretune/utils/notebook_docs.py",
    "run_nbstripout_hook.py": "scripts/run_nbstripout_hook.py",
}


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _read_manifest() -> tuple[str, dict[str, str]]:
    """The upstream commit the files were synced from, and each file's recorded hash."""
    ref, hashes = "", {}
    for line in MANIFEST.read_text().splitlines():
        line = line.strip()
        if line.startswith("# ref:"):
            ref = line.split(":", 1)[1].strip()
        elif line and not line.startswith("#"):
            digest, _, name = line.partition("  ")
            hashes[name] = digest
    return ref, hashes


def _fetch(ref: str, upstream_path: str) -> bytes:
    url = f"https://raw.githubusercontent.com/{UPSTREAM_REPO}/{ref}/{upstream_path}"
    with urllib.request.urlopen(url, timeout=30) as resp:  # (a fixed https URL)
        return resp.read()


def check() -> int:
    if not MANIFEST.exists():
        # a missing manifest fails rather than skips: a skip would look exactly like a pass
        print(f"error: {MANIFEST.relative_to(REPO)} is missing, so the vendored notebook tooling cannot be verified.")
        return 1
    ref, hashes = _read_manifest()
    problems = []
    for name in UPSTREAM_PATHS:
        path = VENDOR_DIR / name
        if name not in hashes:
            problems.append(f"{name}: not in the manifest")
        elif not path.exists():
            problems.append(f"{name}: missing")
        elif _sha256(path.read_bytes()) != hashes[name]:
            problems.append(f"{name}: modified")
    if problems:
        print(f"error: the notebook tooling vendored from {UPSTREAM_REPO}@{ref} does not match its manifest:")
        for p in problems:
            print(f"       {p}")
        print("       Make the change in interpretune, then run this script with --sync <commit>.")
        return 1
    return 0


def sync(ref: str) -> int:
    lines = [
        f"# Notebook tooling vendored unmodified from https://github.com/{UPSTREAM_REPO}.",
        "# Regenerated by `python scripts/check_vendored_notebook_tooling.py --sync <ref>`; do not edit by hand.",
        f"# ref: {ref}",
    ]
    for name, upstream_path in UPSTREAM_PATHS.items():
        data = _fetch(ref, upstream_path)
        (VENDOR_DIR / name).write_bytes(data)
        lines.append(f"{_sha256(data)}  {name}")
        print(f"synced {name} from {upstream_path}@{ref}")
    MANIFEST.write_text("\n".join(lines) + "\n")
    return 0


def upstream(ref: str) -> int:
    pinned, hashes = _read_manifest()
    moved = [name for name, path in UPSTREAM_PATHS.items() if _sha256(_fetch(ref, path)) != hashes.get(name)]
    if moved:
        print(f"{UPSTREAM_REPO}@{ref} differs from the vendored copy (synced from {pinned}): {', '.join(moved)}")
        return 1
    print(f"the vendored copy matches {UPSTREAM_REPO}@{ref}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--sync", metavar="REF", help="fetch the vendored files at this interpretune commit")
    group.add_argument("--upstream", metavar="REF", nargs="?", const="main", help="compare with an upstream ref")
    args = parser.parse_args(argv)
    if args.sync:
        return sync(args.sync)
    if args.upstream:
        return upstream(args.upstream)
    return check()


if __name__ == "__main__":
    sys.exit(main())
